--The banking DBMS (Database Management System) is a relational database management system used to manage common banking operations including:
1.	Transfers 
2.	Deposits 
3.	Withdrawals 
4.	Customers 
5.	Registration
6.	Loans 
7.	Fraud detection and so on
This project demonstrates the use of SQL concept such as database creation, table creation, stored procedures, constraints, indexing, CTE and fraud detection query.
                                      Objectives
•	Design a well-structured banking database
•	Establish relationships between various tables within the database
•	Maintain data integrity and ensure its security
•	Detect fraudulent Transactions
•	Analyze query performance and
•	The use of stored procedures
       Database Structure
The database is named “TABLES”
Customers----------------- Accounts-----------------------Transactions
Customers-----------------Loans----------------------------LoanRepayment
Customers-----------------Accounts------------------Beneficiaries
                                  Conclusion
This project demonstrates how a relational database can be designed for banking operations while maintaining data integrity, security validation, fraud detection and optimum performance.
The use of stored procedures provides reusable business operations for seamless transactions and further queries.
Overall, this project demonstrates practical application of SQL in developing a structured banking database system.

